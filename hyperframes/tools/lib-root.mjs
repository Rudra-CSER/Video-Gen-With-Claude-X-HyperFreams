export function slotHtml(id, start, duration) {
  return `    <div id="el-${id}" data-composition-id="${id}" data-composition-src="compositions/${id}.html"
         data-start="${r3(start)}" data-duration="${r3(duration)}" data-track-index="1" data-width="1920" data-height="1080"></div>`;
}

// Burned-in captions: one timed wrapper per caption holding a positioned .cap box.
// A "\n" in the storyboard text is the intended line break: each line gets its own plate.
// `offset` shifts storyboard (global) times into the composition's time base.
export function captionsHtml(caps, offset = 0) {
  const items = caps.map((c, i) => ({ ...c, id: `cap-${String(i + 1).padStart(3, '0')}`, s: r3(c.start - offset), e: r3(c.end - offset) }));
  const html = items.map((c) => {
    const lines = c.text.split(/\s*\n\s*/).map((l) => l.trim()).filter(Boolean)
      .map((l) => `<span class="cap-line"><span class="cap-in">${esc(l)}</span></span>`).join('');
    return `    <div id="${c.id}" class="clip" data-start="${c.s}" data-duration="${r3(c.e - c.s)}" data-track-index="5">
      <div class="cap ${c.center ? 'cap--center' : 'cap--left'}" id="${c.id}-t">${lines}</div>
    </div>`;
  }).join('\n');
  const tlJs = items.map((c) => `      tl.fromTo('#${c.id}-t', { opacity: 0, y: 10 }, { opacity: 1, y: 0, duration: 0.22, ease: 'power2.out' }, ${c.s});
      tl.to('#${c.id}-t', { opacity: 0, duration: 0.18, ease: 'power1.in' }, ${r3(c.e - 0.18)});`).join('\n');
  return `<!doctype html>
<html lang="en">
<head><meta charset="UTF-8" /><!-- Generated (burned-in narration captions). Edit storyboard/scene-timing.json, then rebuild. --></head>
<body>
  <template id="captions-template">
    <link rel="stylesheet" href="assets/css/kit.css" />
    <style>
      #root { position: absolute; inset: 0; pointer-events: none; }
    </style>
    <div id="root" data-composition-id="captions" data-width="1920" data-height="1080">
${html}
    </div>
    <script>
      const tl = gsap.timeline({ paused: true });
${tlJs}
      window.__timelines['captions'] = tl;
    </script>
  </template>
</body>
</html>
`;
}
