// Shared pieces of the root orchestrator, used by build-root.mjs (the film) and
// preview-scene.mjs (a one-scene preview project that looks exactly like the film).
import { readFile } from 'node:fs/promises';
import path from 'node:path';

export const HF = path.resolve(new URL('..', import.meta.url).pathname);
export const VP = path.resolve(HF, '..');
export const r3 = (n) => +(+n).toFixed(3);
export const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 28);
export const sceneId = (s) => `s${String(s.id).replace(/\D/g, '').padStart(2, '0')}-${slug(s.compositionName || s.title)}`;

export async function loadStoryboard() {
  const sb = JSON.parse(await readFile(path.join(VP, 'storyboard/scene-timing.json'), 'utf8'));
  const layout = JSON.parse(await readFile(path.join(VP, 'storyboard/layout.json'), 'utf8').catch(() => '{}'));
  const boundary = JSON.parse(await readFile(path.join(HF, 'assets/data/campus-boundary.json'), 'utf8'));
  const total = r3(sb.totalSeconds ?? sb.scenes.at(-1).end);
  return { sb, layout, boundary, total };
}

// The background drifts once across the whole film. A preview of [start, end] starts and
// ends in the same state the film has at those times (sine.inOut sampled at the edges).
const sineInOut = (p) => -(Math.cos(Math.PI * p) - 1) / 2;
const lerp = (a, b, p) => a + (b - a) * p;
const DRIFT = [
  ['#bg-glow-a', { x: 0, y: 0 }, { x: -420, y: 160 }, 'sine'],
  ['#bg-glow-b', { x: 0, y: 0 }, { x: 520, y: -140 }, 'sine'],
  ['#bg-outline', { x: 0, y: 0, rotation: -4, scale: 1 }, { x: -160, y: -40, rotation: 2, scale: 1.06 }, 'linear'],
];
function driftScript(filmTotal, start, end) {
  const dur = r3(end - start);
  if (start === 0 && Math.abs(end - filmTotal) < 1e-6) {
    return DRIFT.map(([sel, a, b, e]) => `    tl.fromTo('${sel}', ${JSON.stringify(a)}, ${JSON.stringify({ ...b, duration: dur, ease: e === 'sine' ? 'sine.inOut' : 'none' })}, 0);`).join('\n');
  }
  const at = (a, b, e, t) => {
    const p = e === 'sine' ? sineInOut(t / filmTotal) : t / filmTotal;
    return Object.fromEntries(Object.keys(a).map((k) => [k, r3(lerp(a[k], b[k], p))]));
  };
  return DRIFT.map(([sel, a, b, e]) => `    tl.fromTo('${sel}', ${JSON.stringify(at(a, b, e, start))}, ${JSON.stringify({ ...at(a, b, e, end), duration: dur, ease: 'none' })}, 0);`).join('\n');
}

